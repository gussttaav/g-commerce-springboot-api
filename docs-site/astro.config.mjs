// @ts-check
import starlight from '@astrojs/starlight';
import { scalarStarlight } from '@scalar/starlight';
import { defineConfig } from 'astro/config';
import starlightLinksValidator from 'starlight-links-validator';

const repository = 'https://github.com/gussttaav/g-commerce-springboot-api';

// Vercel sets the production domain at build time; it enables the sitemap and canonical URLs
const productionDomain = process.env.VERCEL_PROJECT_PRODUCTION_URL;

// https://astro.build/config
export default defineConfig({
  site: productionDomain ? `https://${productionDomain}` : undefined,
  integrations: [
    starlight({
      title: 'G-Commerce API',
      description:
        'Developer documentation and interactive API reference of the G-Commerce API: authentication, products, purchases and more.',
      logo: { src: './src/assets/logo.svg', replacesTitle: false },
      favicon: '/favicon.svg',
      social: [{ icon: 'github', label: 'GitHub', href: repository }],
      editLink: { baseUrl: `${repository}/edit/main/docs-site/` },
      customCss: ['./src/styles/custom.css'],
      sidebar: [
        { label: 'Introduction', slug: 'introduction' },
        { label: 'Quickstart', slug: 'quickstart' },
        {
          label: 'Guides',
          items: [
            { slug: 'guides/authentication' },
            { slug: 'guides/errors' },
            { slug: 'guides/pagination' },
            { slug: 'guides/rate-limits' },
          ],
        },
        { label: 'Changelog', slug: 'changelog' },
      ],
      plugins: [
        // Fails the build on broken links between pages; the API reference routes are generated by Scalar
        starlightLinksValidator({ exclude: ['/api-reference', '/api-reference/', '/api-reference/**', '/openapi.json'] }),
        // Renders the published OpenAPI document (public/openapi.json, generated by OpenApiSpecTest)
        // at /api-reference, with a console that sends requests straight to the API
        scalarStarlight({
          label: 'API Reference',
          configuration: {
            url: '/openapi.json',
            persistAuth: true,
            authentication: { preferredSecurityScheme: 'bearerAuth' },
            defaultHttpClient: { targetKey: 'shell', clientKey: 'curl' },
            documentDownloadType: 'json',
            showDeveloperTools: 'never',
            // No third-party services: no AI chat, MCP offer or usage telemetry sent to Scalar
            agent: { disabled: true },
            mcp: { disabled: true },
            telemetry: false,
          },
        }),
      ],
    }),
  ],
});
